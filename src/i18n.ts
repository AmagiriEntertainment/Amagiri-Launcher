const tables: Record<string, Record<keyof typeof en, string>> = { English: en, 'Bahasa Indonesia': id, '日本語': ja }
export type CopyKey = keyof typeof en

export function tr(lang: string, key: CopyKey, vars?: Record<string, string | number>) {
  const text = tables[lang]?.[key] ?? en[key]
  if (!vars) return text
  return text.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ''))
}

